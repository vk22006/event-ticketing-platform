use rand::RngCore;
use std::path::{Path, PathBuf};

/// Maximum allowed file size for event banner uploads (5 MB).
pub const MAX_BANNER_SIZE: usize = 5 * 1024 * 1024;

/// Permitted image MIME types and formats.
pub const ALLOWED_FORMATS_DESC: &str = "JPEG, PNG, WebP, and GIF";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AllowedImageFormat {
    Jpeg,
    Png,
    WebP,
    Gif,
}

impl AllowedImageFormat {
    pub fn extension(&self) -> &'static str {
        match self {
            AllowedImageFormat::Jpeg => "jpg",
            AllowedImageFormat::Png => "png",
            AllowedImageFormat::WebP => "webp",
            AllowedImageFormat::Gif => "gif",
        }
    }

    pub fn mime_type(&self) -> &'static str {
        match self {
            AllowedImageFormat::Jpeg => "image/jpeg",
            AllowedImageFormat::Png => "image/png",
            AllowedImageFormat::WebP => "image/webp",
            AllowedImageFormat::Gif => "image/gif",
        }
    }

    /// Inspect magic bytes / file signatures to verify authentic image content.
    /// Does not trust the submitted filename extension or Content-Type header.
    pub fn detect(bytes: &[u8]) -> Option<Self> {
        // JPEG starts with FF D8 FF
        if bytes.len() >= 3 && bytes[0..3] == [0xFF, 0xD8, 0xFF] {
            return Some(AllowedImageFormat::Jpeg);
        }
        // PNG starts with 89 50 4E 47 0D 0A 1A 0A
        if bytes.len() >= 8 && bytes[0..8] == [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A] {
            return Some(AllowedImageFormat::Png);
        }
        // GIF starts with GIF87a or GIF89a
        if bytes.len() >= 6 && (bytes[0..6] == *b"GIF87a" || bytes[0..6] == *b"GIF89a") {
            return Some(AllowedImageFormat::Gif);
        }
        // WebP starts with RIFF....WEBP
        if bytes.len() >= 12 && bytes[0..4] == *b"RIFF" && bytes[8..12] == *b"WEBP" {
            return Some(AllowedImageFormat::WebP);
        }
        None
    }
}

#[derive(Debug, thiserror::Error)]
pub enum UploadError {
    #[error("Uploaded file exceeds the maximum allowed size of 5 MB.")]
    FileTooLarge,
    #[error(
        "Invalid or unsupported image format. Only JPEG, PNG, WebP, and GIF images are allowed."
    )]
    UnsupportedFormat,
    #[error("Uploaded file is empty.")]
    EmptyFile,
    #[error("Failed to read upload data.")]
    StreamError,
    #[error("Failed to store uploaded file on disk.")]
    StorageError,
}

/// Generates a server-controlled, cryptographically random, unguessable filename.
/// Format: `event-{timestamp_ms}-{16_random_hex_chars}.{ext}`
pub fn generate_banner_filename(ext: &str) -> String {
    let now = chrono::Utc::now().timestamp_millis();
    let mut rand_bytes = [0u8; 8];
    rand::thread_rng().fill_bytes(&mut rand_bytes);
    let hex_rand = rand_bytes
        .iter()
        .map(|b| format!("{:02x}", b))
        .collect::<String>();
    format!("event-{}-{}.{}", now, hex_rand, ext)
}

/// Validates file content and writes the banner to disk in the configured upload directory.
/// Returns the relative URL path (e.g. `/uploads/event-...`) and the absolute disk PathBuf.
pub async fn save_banner_upload(
    upload_dir: &Path,
    data: &[u8],
) -> Result<(String, PathBuf), UploadError> {
    if data.is_empty() {
        return Err(UploadError::EmptyFile);
    }
    if data.len() > MAX_BANNER_SIZE {
        return Err(UploadError::FileTooLarge);
    }

    let format = AllowedImageFormat::detect(data).ok_or(UploadError::UnsupportedFormat)?;
    let filename = generate_banner_filename(format.extension());
    let dest_path = upload_dir.join(&filename);

    tokio::fs::write(&dest_path, data).await.map_err(|err| {
        tracing::error!(error = %err, "Failed to write banner upload to disk");
        UploadError::StorageError
    })?;

    let relative_url = format!("/uploads/{}", filename);
    Ok((relative_url, dest_path))
}

/// Safely removes a superseded or orphaned banner file from the storage directory.
/// Strictly enforces that the file path is within `upload_dir` and begins with `event-`
/// to prevent accidental deletion of seed assets or traversal attacks.
pub async fn remove_banner_file(upload_dir: &Path, banner_url: &str) {
    let filename = match banner_url.strip_prefix("/uploads/") {
        Some(name) => name,
        None => return,
    };

    // Prevent directory traversal
    if filename.contains('/') || filename.contains('\\') || filename.contains("..") {
        tracing::warn!(filename, "Rejected unsafe banner filename deletion attempt");
        return;
    }

    // Only delete files generated by our event banner uploader (starting with event- and containing a second hyphen)
    // Seed files like event-1772530115548.jpg have only 1 hyphen; dynamic files have event-{ts}-{rand}.{ext}
    let parts: Vec<&str> = filename.split('-').collect();
    if parts.len() < 3 || parts[0] != "event" {
        tracing::debug!(
            filename,
            "Skipping deletion of non-dynamic or seed banner file"
        );
        return;
    }

    let path = upload_dir.join(filename);
    if path.exists() {
        if let Err(err) = tokio::fs::remove_file(&path).await {
            tracing::warn!(error = %err, path = ?path, "Failed to remove replaced banner file");
        } else {
            tracing::info!(path = ?path, "Removed replaced banner file");
        }
    }
}

pub struct ParsedMultipart {
    pub fields: std::collections::HashMap<String, String>,
    pub banner: Option<(String, PathBuf)>,
}

/// Parses a multipart request with streaming chunk reading to prevent unbounded memory consumption.
/// If an error occurs after a banner file has been written to disk, the file is cleaned up before returning Err.
pub async fn parse_multipart_form(
    mut multipart: axum::extract::Multipart,
    upload_dir: &Path,
) -> Result<ParsedMultipart, UploadError> {
    let mut fields = std::collections::HashMap::new();
    let mut banner: Option<(String, PathBuf)> = None;

    let res: Result<(), UploadError> = async {
        while let Some(mut field) = multipart.next_field().await.map_err(|err| {
            tracing::warn!(error = %err, "Error reading multipart field");
            UploadError::StreamError
        })? {
            let name = field.name().unwrap_or("").to_string();
            if name == "banner_image" {
                let filename_opt = field.file_name().map(str::to_string);
                let mut data = Vec::new();
                let mut exceeded = false;

                while let Some(chunk) = field.chunk().await.map_err(|err| {
                    tracing::warn!(error = %err, "Error reading multipart file chunk");
                    UploadError::StreamError
                })? {
                    if data.len() + chunk.len() > MAX_BANNER_SIZE {
                        exceeded = true;
                        break;
                    }
                    data.extend_from_slice(&chunk);
                }

                if exceeded {
                    return Err(UploadError::FileTooLarge);
                }

                let has_filename = filename_opt.as_ref().is_some_and(|f| !f.trim().is_empty());
                if !data.is_empty() {
                    if let Some((_, ref prev_path)) = banner {
                        let _ = tokio::fs::remove_file(prev_path).await;
                    }
                    let saved = save_banner_upload(upload_dir, &data).await?;
                    banner = Some(saved);
                } else if has_filename {
                    return Err(UploadError::EmptyFile);
                }
            } else if !name.is_empty() {
                let mut text_bytes = Vec::new();
                while let Some(chunk) = field.chunk().await.map_err(|_| UploadError::StreamError)? {
                    if text_bytes.len() + chunk.len() <= 64 * 1024 {
                        text_bytes.extend_from_slice(&chunk);
                    }
                }
                if let Ok(text) = String::from_utf8(text_bytes) {
                    fields.insert(name, text);
                }
            }
        }
        Ok(())
    }
    .await;

    match res {
        Ok(()) => Ok(ParsedMultipart { fields, banner }),
        Err(err) => {
            if let Some((_, ref path)) = banner {
                let _ = tokio::fs::remove_file(path).await;
            }
            Err(err)
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_magic_bytes_detection_jpeg() {
        let jpeg_header = [0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46];
        assert_eq!(
            AllowedImageFormat::detect(&jpeg_header),
            Some(AllowedImageFormat::Jpeg)
        );
    }

    #[test]
    fn test_magic_bytes_detection_png() {
        let png_header = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00];
        assert_eq!(
            AllowedImageFormat::detect(&png_header),
            Some(AllowedImageFormat::Png)
        );
    }

    #[test]
    fn test_magic_bytes_detection_gif() {
        let gif87 = b"GIF87a\x01\x00\x01\x00";
        let gif89 = b"GIF89a\x01\x00\x01\x00";
        assert_eq!(
            AllowedImageFormat::detect(gif87),
            Some(AllowedImageFormat::Gif)
        );
        assert_eq!(
            AllowedImageFormat::detect(gif89),
            Some(AllowedImageFormat::Gif)
        );
    }

    #[test]
    fn test_magic_bytes_detection_webp() {
        let webp_header = b"RIFF\x20\x00\x00\x00WEBPVP8 ";
        assert_eq!(
            AllowedImageFormat::detect(webp_header),
            Some(AllowedImageFormat::WebP)
        );
    }

    #[test]
    fn test_magic_bytes_rejection_disguised_files() {
        // Text / script disguised as image
        let script = b"<?php echo 'malicious'; ?>";
        assert_eq!(AllowedImageFormat::detect(script), None);

        // HTML disguised as image
        let html = b"<!DOCTYPE html><html><body>malicious</body></html>";
        assert_eq!(AllowedImageFormat::detect(html), None);

        // PDF disguised as image
        let pdf = b"%PDF-1.4 ...";
        assert_eq!(AllowedImageFormat::detect(pdf), None);

        // Executable / ELF
        let elf = b"\x7FELF\x02\x01\x01\x00";
        assert_eq!(AllowedImageFormat::detect(elf), None);
    }

    #[test]
    fn test_filename_generation_format_and_uniqueness() {
        let name1 = generate_banner_filename("jpg");
        let name2 = generate_banner_filename("jpg");
        assert_ne!(name1, name2);
        assert!(name1.starts_with("event-"));
        assert!(name1.ends_with(".jpg"));
        let parts: Vec<&str> = name1.split('-').collect();
        assert_eq!(parts.len(), 3);
    }
}
